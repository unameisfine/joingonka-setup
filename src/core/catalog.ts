/**
 * Каталог моделей ОДНОЙ установки — то, что адаптер пишет в каталог провайдера.
 *
 * Обычно это актуальные модели сети (OPENCLAW_MODELS). Исключение — явный
 * `--model` с id вне каталога установщика: сеть может получить модель раньше, чем
 * выйдет новая версия пакета, и разбор моделей (core/models.ts) пропускает такой id
 * с предупреждением. Но записать его только в «модель по умолчанию» мало: у
 * инструментов с каталогом провайдера (opencode, Kilo, OpenClaw, Pi, Zed, Crush,
 * Droid, …) модель, которой в каталоге НЕТ, не находится вовсе — дефолт молча
 * отбрасывается либо сессия падает с «model not found». Поэтому такая модель
 * попадает и в каталог — с ОСТОРОЖНЫМИ лимитами: окно по умолчанию и наименьший
 * потолок ответа по каталогу (занизить безопаснее, чем пообещать инструменту окно,
 * которого у модели нет, — он перестанет вовремя сжимать историю).
 *
 * ★ До второй части 0.5.0 функция жила пятью копиями в новых адаптерах, а старые
 * (opencode, kilo, openclaw, pi, zed) её не имели вовсе — у них `--model <новый id>`
 * давал конфиг с дефолтом, которого инструмент не знает.
 *
 * ★ Граница, которую функция НЕ двигает: без `--model` каталог — только модели
 * сети. Поэтому повторный запуск без флага считает прежнюю модель вне каталога
 * «ушедшей» и возвращает дефолт. Это осознанно: установщик не может отличить
 * модель, которой в сети ЕЩЁ нет в его каталоге, от той, которой УЖЕ нет, — а
 * мёртвая ссылка хуже сброшенной. Об этом говорит предупреждение core/models.ts.
 */
import { OPENCLAW_MODELS, type OpenClawModelSpec } from '../constants.js';

/** Что каталогу нужно знать о запуске (подмножество ApplyInput). */
export interface CatalogInput {
  model: string;
  modelExplicit?: boolean;
}

/** Актуальные id моделей сети — по ним адаптеры узнают ссылку на ушедшую модель. */
export const NETWORK_MODEL_IDS: readonly string[] = OPENCLAW_MODELS.map((m) => m.id);

/** Наименьший потолок ответа по каталогу — осторожное значение для незнакомой модели. */
function conservativeMaxTokens(): number {
  return Math.min(...OPENCLAW_MODELS.map((m) => m.maxTokens));
}

/** Модели, которые эта установка пишет в каталог провайдера (см. шапку модуля). */
export function catalogFor(input: CatalogInput): OpenClawModelSpec[] {
  const specs = [...OPENCLAW_MODELS];
  if (input.modelExplicit && !NETWORK_MODEL_IDS.includes(input.model)) {
    // `contextWindow` не задаём: адаптеры подставят окно по умолчанию.
    specs.push({ id: input.model, name: input.model, maxTokens: conservativeMaxTokens() });
  }
  return specs;
}

/**
 * Id моделей каталога этой установки — по ним адаптер решает, какая ссылка на
 * НАШУ модель мертва. Именно каталог установки, а не сети: модель, только что
 * запрошенная явным `--model` и записанная в каталог, — живая, и называть её
 * «ушедшей из сети» (а повторный запуск с тем же флагом — «чисткой») нельзя.
 */
export function catalogIds(input: CatalogInput): string[] {
  return catalogFor(input).map((spec) => spec.id);
}
